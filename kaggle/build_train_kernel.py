"""Bundle submission/isu_core.py + train/train_isu.py into one Kaggle script kernel.

Usage: python -I kaggle/build_train_kernel.py --transformers 4.57.1 [--slug isu-track-b-train]
Then:  kaggle kernels push -p kaggle/isu-train --accelerator NvidiaTeslaT4
The shared core is inlined (not re-implemented), so Kaggle trains exactly the code that ships.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

ap = argparse.ArgumentParser()
ap.add_argument("--transformers", required=True, help="exact version resolved in isu-challenge-base")
ap.add_argument("--slug", default="isu-track-b-train")
ap.add_argument("--user", default="nitishxdandu")
ap.add_argument("--data-kernel", default="isu-track-b-data")
ap.add_argument("--variant", default="v1", help="training variant (VARIANTS in train/train_isu.py)")
args = ap.parse_args()

core = (ROOT / "submission" / "isu_core.py").read_text(encoding="utf-8")
train = (ROOT / "train" / "train_isu.py").read_text(encoding="utf-8")
train = "\n".join(l for l in train.splitlines() if "# BUNDLE-STRIP" not in l)
assert "__TRANSFORMERS_PIN__" in train
train = train.replace("__TRANSFORMERS_PIN__", args.transformers)
assert '"__VARIANT__"' in train and f'"{args.variant}": ' in train, f"unknown variant {args.variant}"
train = train.replace('VARIANT = "__VARIANT__"', f'VARIANT = "{args.variant}"')
digest = hashlib.sha256((core + train).encode()).hexdigest()[:12]
bundle = (f"# AUTO-GENERATED by kaggle/build_train_kernel.py (bundle {digest}); edit the sources instead.\n"
          f"# ===== submission/isu_core.py =====\n{core}\n\n# ===== train/train_isu.py =====\n{train}\n")
compile(bundle, "train_kernel.py", "exec")  # syntax check before pushing

out = ROOT / "kaggle" / args.slug.replace("isu-track-b-", "isu-")
out.mkdir(parents=True, exist_ok=True)
(out / "train_kernel.py").write_text(bundle, encoding="utf-8")
(out / "kernel-metadata.json").write_text(json.dumps({
    "id": f"{args.user}/{args.slug}",
    "title": args.slug,
    "code_file": "train_kernel.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_tpu": False,
    "enable_internet": True,
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [f"{args.user}/{args.data_kernel}"],
}, indent=2))
print(f"wrote {out / 'train_kernel.py'} (bundle {digest}, variant {args.variant})")
