"""Bundle submission/isu_core.py + a tools/ script into one Kaggle script kernel.

Usage: python -I kaggle/build_check_kernel.py --transformers 4.57.6 [--script tools/kaggle_checks.py]
           [--slug isu-track-b-checks] [--sources isu-track-b-data,isu-track-b-train-v2]
Then:  kaggle kernels push -p kaggle/<slug minus "isu-track-b-" prefix as isu-...> --accelerator NvidiaTeslaT4
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument("--transformers", required=True)
ap.add_argument("--user", default="nitishxdandu")
ap.add_argument("--script", default="tools/kaggle_checks.py")
ap.add_argument("--slug", default="isu-track-b-checks")
ap.add_argument("--sources", default="isu-track-b-data,isu-track-b-train-v2")
args = ap.parse_args()

core = (ROOT / "submission" / "isu_core.py").read_text(encoding="utf-8")
body = (ROOT / args.script).read_text(encoding="utf-8")
body = "\n".join(l for l in body.splitlines() if "# BUNDLE-STRIP" not in l)
assert "__TRANSFORMERS_PIN__" in body
body = body.replace("__TRANSFORMERS_PIN__", args.transformers)
# isu_core has `from __future__ import annotations`, which must stay first: put the core first.
bundle = f"# AUTO-GENERATED by kaggle/build_check_kernel.py from {args.script}; edit the sources instead.\n{core}\n\n{body}\n"
compile(bundle, "kernel.py", "exec")
out = ROOT / "kaggle" / args.slug.replace("isu-track-b-", "isu-")
out.mkdir(parents=True, exist_ok=True)
(out / "kernel.py").write_text(bundle, encoding="utf-8")
(out / "kernel-metadata.json").write_text(json.dumps({
    "id": f"{args.user}/{args.slug}", "title": args.slug, "code_file": "kernel.py",
    "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
    "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "competition_sources": [],
    "kernel_sources": [f"{args.user}/{s}" for s in args.sources.split(",")],
}, indent=2))
print(f"wrote {out / 'kernel.py'}")
